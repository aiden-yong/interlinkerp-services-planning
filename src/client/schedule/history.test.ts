import { describe, expect, it } from 'vitest';
import type { HistoryEntry } from '../types';
import { describeEntry } from './history';

const entry = (over: Partial<HistoryEntry>): HistoryEntry => ({ action: 'created', actor: 'a@x.com', actor_kind: 'manager', actor_name: 'Alice', changes: null, at: '2026-10-21T01:00:00Z', ...over });

describe('describeEntry', () => {
  it('describes a change with names and local times', () => {
    const e = entry({
      action: 'changed',
      changes: { note: ['', 'Bring keys'], start_at: ['2026-10-22T01:00:00Z', '2026-10-22T02:00:00Z'], role_id: ['r1', 'r2'], employee_ref: ['e1', null] },
    });
    const out = describeEntry(e, 'Asia/Kuala_Lumpur', [{ id: 'r1', name: 'Cashier' }, { id: 'r2', name: 'Cook' }], new Map([['e1', 'Bob']]));
    expect(out.text).toBe('Changed by Alice: Employee Bob → Open shift, Role Cashier → Cook, Start 09:00 → 10:00, Note "" → "Bring keys"');
    expect(out.when).toBe('21 Oct 2026 09:00');
  });

  it('describes an unknown actor', () => {
    expect(describeEntry(entry({ actor_name: '', actor: null }), 'UTC', [], new Map()).text).toBe('Created by someone');
  });

  it('describes system and Auto Plan entries', () => {
    expect(describeEntry(entry({ action: 'generated', actor_kind: 'system', actor_name: 'System' }), 'UTC', [], new Map()).text).toBe('Generated by the repeat');
    expect(describeEntry(entry({ action: 'auto_planned' }), 'UTC', [], new Map()).text).toBe('Assigned by Auto Plan (run by Alice)');
    expect(describeEntry(entry({ action: 'unassigned' }), 'UTC', [], new Map()).text).toBe('Given up by Alice');
  });
});

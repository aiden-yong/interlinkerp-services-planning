import { DateTime } from 'luxon';
import type { HistoryEntry } from '../types';

const LABELS: Record<string, string> = {
  employee_ref: 'Employee', role_id: 'Role', start_at: 'Start', end_at: 'End', break_minutes: 'Break', allocated_percent: 'Allocation', note: 'Note',
};
const ORDER = Object.keys(LABELS);

const VERBS: Record<string, string> = {
  created: 'Created by', published: 'Published by', deleted: 'Deleted by', restored: 'Restored by', split: 'Split by',
  copied: 'Copied from last week by', claimed: 'Claimed by', switch_requested: 'Put up for switch by',
  switch_cancelled: 'Switch request cancelled by', taken_over: 'Taken over by', unassigned: 'Given up by',
};

type Roles = { id: string; name: string }[];

// Times show as HH:mm; the date is added only when the two sides fall on different days.
function instant(value: unknown, zone: string, other: unknown): string {
  if (typeof value !== 'string') return '(none)';
  const t = DateTime.fromISO(value, { zone });
  if (!t.isValid) return value;
  const o = typeof other === 'string' ? DateTime.fromISO(other, { zone }) : null;
  return o?.isValid && o.toISODate() === t.toISODate() ? t.toFormat('HH:mm') : t.toFormat('d MMM HH:mm');
}

function show(key: string, v: unknown, other: unknown, zone: string, roles: Roles, names: Map<string, string>): string {
  switch (key) {
    case 'employee_ref': return v == null ? 'Open shift' : names.get(String(v)) ?? 'someone';
    case 'role_id': return v == null ? 'No role' : roles.find((r) => r.id === v)?.name ?? 'a removed role';
    case 'start_at':
    case 'end_at': return instant(v, zone, other);
    case 'break_minutes': return `${v ?? 0} min`;
    case 'allocated_percent': return `${v}%`;
    case 'note': return `"${v ?? ''}"`;
    default: return String(v);
  }
}

export function describeEntry(e: HistoryEntry, zone: string, roles: Roles, names: Map<string, string>): { when: string; text: string } {
  const when = DateTime.fromISO(e.at, { zone }).toFormat('d MMM yyyy HH:mm');
  const who = e.actor_name || 'someone';
  if (e.action === 'generated') return { when, text: e.actor_kind === 'system' ? 'Generated by the repeat' : `Generated by ${who}` };
  if (e.action === 'auto_planned') return { when, text: `Assigned by Auto Plan (run by ${who})` };
  if (e.action === 'changed') {
    const changes = e.changes ?? {};
    const parts = ORDER.filter((k) => k in changes).map((k) => {
      const [from, to] = changes[k]!;
      return `${LABELS[k]} ${show(k, from, to, zone, roles, names)} → ${show(k, to, from, zone, roles, names)}`;
    });
    return { when, text: parts.length ? `Changed by ${who}: ${parts.join(', ')}` : `Changed by ${who}` };
  }
  return { when, text: `${VERBS[e.action] ?? `${e.action} by`} ${who}` };
}
